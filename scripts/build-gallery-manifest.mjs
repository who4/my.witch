import { mkdir, readdir, writeFile } from "node:fs/promises";
import { extname, relative, resolve, sep } from "node:path";

const root = resolve(import.meta.dirname, "..");
const photoDirectory = resolve(root, "gallery-photos");
const manifestPath = resolve(root, "gallery-manifest.js");
const supportedExtensions = new Set([".avif", ".gif", ".jpeg", ".jpg", ".png", ".webp"]);

async function collectPhotos(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const photos = await Promise.all(entries.map(async (entry) => {
    const fullPath = resolve(directory, entry.name);
    if (entry.isDirectory()) return collectPhotos(fullPath);
    if (!entry.isFile() || !supportedExtensions.has(extname(entry.name).toLowerCase())) return [];
    return [relative(root, fullPath).split(sep).map(encodeURIComponent).join("/")];
  }));
  return photos.flat();
}

await mkdir(photoDirectory, { recursive: true });
const photos = (await collectPhotos(photoDirectory)).sort((a, b) => a.localeCompare(b));
const contents = `// Generated by scripts/build-gallery-manifest.mjs. Do not edit manually.\nwindow.GALLERY_PHOTOS = ${JSON.stringify(photos, null, 2)};\n`;
await writeFile(manifestPath, contents, "utf8");
console.log(`Gallery manifest updated with ${photos.length} photo${photos.length === 1 ? "" : "s"}.`);
